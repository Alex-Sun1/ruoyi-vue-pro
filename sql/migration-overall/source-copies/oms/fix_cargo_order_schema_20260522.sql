  `address_type`                varchar(32)     DEFAULT NULL                COMMENT '地址类型(PLATFORM_WH/PRIVATE/COMMERCIAL)',
  `platform_warehouse_code`     varchar(64)     DEFAULT NULL                COMMENT '平台仓库代码',
