-- 注意：此操作会清空以下表的现有数据：
--   oms_cargo_order
--   oms_cargo_order_shipment
--   oms_cargo_order_sku_item
--   oms_cargo_order_node_trace
--   oms_container_cargo_order_rel（关联表数据，一并清理再重插）
-- =================================================================

