-- =================================================================
-- 货物订单表结构修复脚本
-- 问题：oms_cargo_order / oms_cargo_order_shipment 使用旧 schema，
--       与 CargoOrder.java / CargoOrderShipment.java 实体字段不匹配，
--       导致 selectVoList 生成的 SELECT 语句包含数据库中不存在的列，
--       海柜订单详情接口（queryById → cargoOrderMapper.selectVoList）报 500。
